#!/usr/bin/env node
/**
 * Build src/moodle/local_hubredirect/standalone_lessons.json - what a lesson
 * unit MEANS, for every standalone lesson build that reports progress under its
 * own unit ids.
 *
 *   node tools/build-standalone-lesson-map.mjs           # write it
 *   node tools/build-standalone-lesson-map.mjs --check   # fail if it is stale
 *
 * THE UNIT PROBLEM, and what this settles of it. The standalone builds in
 * Mathematics, Science, Computing and Global Perspectives are organised by
 * strand, not by the shell course's term-ordered units, so they write progress
 * under l01..lNN beneath the SAME course key the shell uses
 * (mathematics/lesson-app-tools/wire-progress.py explains why u01 would be a
 * false claim). The live board and resume work off those rows. Two surfaces
 * did not know what they were:
 *
 *   the family portal  divided lessons finished by the CATALOGUE's unit count -
 *                      the shell course's. Maths Grade 2 is 9 lessons against
 *                      15 units, so a child who finished every lesson read
 *                      60%; Science Grade 3 is 13 lessons against 6 units, so a
 *                      child read 100% with seven lessons still to do.
 *   every label        "L03" in the portal, a bare "l03" on the live board and
 *                      the parent board.
 *
 * This map is the answer both needed: for each course key, its lessons in
 * order, by the unit id the build writes and the title its own hub shows. The
 * server uses it only for courses whose rows ARE lesson units, so a course
 * still on the shell - or a build nobody is routed to - is untouched.
 *
 * Read, not retyped: every entry comes from a build's app.config.json, where
 * lessons[] order IS the unit number (`${prefix}${NN}`, the form every kit's
 * build-hub.py and wire-progress.py use). Deterministic - sorted, no
 * timestamps - so --check can byte-compare, and a lesson added, renamed or
 * reordered without a re-run fails it.
 */
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const HERE = path.dirname(fileURLToPath(import.meta.url));
const ROOT = path.resolve(HERE, "..");
const EHEL = path.join(ROOT, "src", "prototypes", "ehel-academy");
const OUT = path.join(ROOT, "src", "moodle", "local_hubredirect", "standalone_lessons.json");
const args = process.argv.slice(2);
for (const a of args) if (a !== "--check") { console.error("unrecognised argument: " + a); process.exit(2); }
const CHECK = args.includes("--check");

// Every build directory that carries an app.config.json: <subject>/grade-N-app,
// and one level below it (Mathematics Grade 1 keeps its live build in g1v2/).
const configs = [];
for (const subject of fs.readdirSync(EHEL, { withFileTypes: true })) {
  if (!subject.isDirectory()) continue;
  const sdir = path.join(EHEL, subject.name);
  for (const g of fs.readdirSync(sdir, { withFileTypes: true })) {
    if (!g.isDirectory() || !/^grade-\d+-app$/.test(g.name)) continue;
    const gdir = path.join(sdir, g.name);
    const cands = [path.join(gdir, "app.config.json")];
    for (const sub of fs.readdirSync(gdir, { withFileTypes: true })) {
      if (sub.isDirectory()) cands.push(path.join(gdir, sub.name, "app.config.json"));
    }
    for (const c of cands) if (fs.existsSync(c)) configs.push(c);
  }
}

const courses = {};
for (const file of configs.sort()) {
  const cfg = JSON.parse(fs.readFileSync(file, "utf8"));
  const prefix = cfg.progressUnitPrefix ?? "l";
  /* u-prefixed builds are HERE TOO since 2026-09-12. English and Art &
     Design write the course's own uNN, so they never needed this map to fix
     a COUNT - the catalogue's unit count is already their lesson count. They
     did need it for NAMES: without an entry every label fell back to a bare
     "Unit 3", where an l-build reads "Lesson 3: Forward, Back, Left, Right".
     The unit id keeps its own prefix, so nothing downstream has to guess. */
  const key = cfg.courseKey;
  const lessons = Array.isArray(cfg.lessons) ? cfg.lessons : [];
  if (!key || !lessons.length) continue;
  if (courses[key]) {
    console.error(`REFUSED: ${key} is described twice (${courses[key].from} and ${path.relative(ROOT, file)})`);
    process.exit(2);
  }
  courses[key] = {
    from: path.relative(ROOT, file).split(path.sep).join("/"),
    lessons: lessons.map((l, i) => {
      if (!l.title) { console.error(`REFUSED: lesson ${i + 1} of ${key} has no title`); process.exit(2); }
      return { unit: prefix + String(i + 1).padStart(2, "0"), title: l.title };
    }),
  };
}
if (Object.keys(courses).length < 10) {
  // a scan that quietly found nothing must not write an empty map the server
  // would then read as "no course has lessons"
  console.error(`REFUSED: only ${Object.keys(courses).length} lesson-unit builds found - the scan is broken`);
  process.exit(2);
}

const map = {
  _comment: "GENERATED by tools/build-standalone-lesson-map.mjs from each standalone build's app.config.json - do not edit. " +
    "For every course key whose standalone build writes progress under its own lesson units (l01..lNN): its lessons in order. " +
    "Read by local_hubredirect/progress_rolluplib.php (pqpr_standalone_lessons) for the family portal's lessons-done count and every lesson label.",
  courses: Object.fromEntries(Object.keys(courses).sort().map((k) => [k, courses[k]])),
};
const text = JSON.stringify(map, null, 2) + "\n";

if (CHECK) {
  const have = fs.existsSync(OUT) ? fs.readFileSync(OUT, "utf8") : "";
  if (have !== text) {
    console.error("standalone_lessons.json is STALE - a build's lessons changed. Run: node tools/build-standalone-lesson-map.mjs");
    process.exit(1);
  }
  console.log(`standalone_lessons.json is current: ${Object.keys(courses).length} courses`);
} else {
  fs.writeFileSync(OUT, text);
  console.log(`wrote ${path.relative(ROOT, OUT)}: ${Object.keys(courses).length} courses`);
}
for (const k of Object.keys(map.courses)) console.log("  " + k.padEnd(16) + String(map.courses[k].lessons.length).padStart(3) + " lessons  " + map.courses[k].from);
