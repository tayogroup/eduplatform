// Repair clipped teaching text in the Mathematics runtime packages, in place.
//
// build-ehel-math-runtime.js used to clip explainers at 520 characters and
// append an ellipsis, leaving 57% of concept fields ending mid-sentence. The
// builder is fixed, but the generated units cannot simply be rebuilt: they
// carry hand-authored work that exists nowhere else (extra concepts, extra
// outcomes, manually completed solutions). Rebuilding would discard it.
//
// So this repairs only what was clipped. For every string ending in an
// ellipsis it finds the source block the text came from and restores the full
// prose, leaving every other byte of the file untouched.
//
//   node tools/repair-ehel-math-truncation.mjs [--write] [grade ...]
//
// Runs as a dry run unless --write is passed.

import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const here = path.dirname(fileURLToPath(import.meta.url));
const root = path.join(here, "..");
const modelPath = path.join(root, "outputs", "019f6433-3b5b-7513-8de4-dfd68b782812", "math-content-model.json");
const mathRoot = path.join(root, "src", "prototypes", "ehel-academy", "mathematics");

const args = process.argv.slice(2);
const write = args.includes("--write");
const onlyGrades = args.filter((a) => /^\d+$/.test(a)).map(Number);

const model = JSON.parse(fs.readFileSync(modelPath, "utf8"));

const tidy = (value = "") => String(value).replace(/�/g, "–").replace(/\s+/g, " ").trim();
const ELLIPSIS = "…";

// Teaching prose: the learner reads this to understand the maths, so a clipped
// value is restored to its full length from the source document.
const PROSE_KEYS = new Set(["explanation", "example", "solution", "answer", "text", "prompt", "modelAnswer", "meaning"]);

// Short derived summaries (a model's `purpose`, an exploration's `context`) are
// generated by clipping the concept explanation to ~220 characters. They are
// captions, not teaching text, so restoring the full prose would bloat the UI.
// Instead trim them back to their last complete sentence — no invented text,
// no sentence left hanging.
const SUMMARY_KEYS = new Set(["purpose", "context"]);

// `hint` is skipped entirely: its ellipses are deliberate, marking a sequence
// the learner continues ("Count forward from 12: 12, 13…").
function trimToSentence(value) {
  const text = value.trimEnd().slice(0, -ELLIPSIS.length).trimEnd();
  const cut = Math.max(text.lastIndexOf(". "), text.lastIndexOf("? "), text.lastIndexOf("! "));
  if (cut > 60) return text.slice(0, cut + 1);
  return /[.?!]$/.test(text) ? text : `${text}.`;
}

// Index every block of a unit once, so a lookup is a scan over one array.
function unitBlocks(grade, unit) {
  const pkg = model.grades[String(grade)];
  if (!pkg) return [];
  const blocks = [];
  for (const doc of pkg.documents) {
    if (doc.unit !== unit) continue;
    for (const block of doc.blocks) {
      const text = tidy(block.text);
      if (text.length > 20) blocks.push(text);
    }
  }
  return blocks;
}

// Find the full text behind a clipped value. The old builder joined up to two
// source paragraphs with a space before clipping, so the clipped value may span
// more than one block; walk forward until the reconstruction is at least as
// long as what we have, then return those blocks as real paragraphs.
function restore(clipped, blocks) {
  const prefix = tidy(clipped.slice(0, clipped.length - ELLIPSIS.length));
  if (prefix.length < 25) return null;
  const probe = prefix.slice(0, Math.min(60, prefix.length));

  const start = blocks.findIndex((block) => block.startsWith(probe));
  if (start === -1) return null;

  const picked = [blocks[start]];
  let joined = blocks[start];
  let cursor = start;
  // Only keep absorbing while the clipped text genuinely runs past what we have
  // and the next block actually continues it.
  while (joined.length < prefix.length && cursor + 1 < blocks.length) {
    const next = blocks[cursor + 1];
    const candidate = `${joined} ${next}`;
    if (!prefix.startsWith(candidate.slice(0, Math.min(prefix.length, candidate.length)))) break;
    picked.push(next);
    joined = candidate;
    cursor += 1;
  }
  if (joined.length < prefix.length) return null;      // reconstruction disagrees
  const restored = picked.join("\n\n");
  if (restored.length <= prefix.length) return null;   // nothing actually gained
  return restored;
}

const stats = { files: 0, changed: 0, clipped: 0, repaired: 0, unmatched: 0, trimmed: 0, charsAdded: 0 };
const unmatchedSamples = [];

const gradeDirs = fs.readdirSync(mathRoot).filter((name) => /^grade-\d+$/.test(name)).sort();
for (const gradeDir of gradeDirs) {
  const grade = Number(gradeDir.split("-")[1]);
  if (onlyGrades.length && !onlyGrades.includes(grade)) continue;
  const unitsDir = path.join(mathRoot, gradeDir, "data", "units");
  if (!fs.existsSync(unitsDir)) continue;

  for (const file of fs.readdirSync(unitsDir).filter((n) => n.endsWith(".json")).sort()) {
    const filePath = path.join(unitsDir, file);
    const raw = fs.readFileSync(filePath, "utf8");
    const unit = JSON.parse(raw);
    stats.files += 1;

    const unitNo = unit.unit?.unitNo ?? Number((file.match(/unit-(\d+)/) || [])[1]);
    const blocks = unitBlocks(grade, unitNo);
    let fileRepairs = 0;

    const visit = (node) => {
      if (Array.isArray(node)) { node.forEach(visit); return; }
      if (!node || typeof node !== "object") return;
      for (const [key, value] of Object.entries(node)) {
        if (typeof value === "string") {
          if (!value.trimEnd().endsWith(ELLIPSIS)) continue;
          if (SUMMARY_KEYS.has(key)) {
            const trimmed = trimToSentence(value);
            if (trimmed && trimmed !== value) { node[key] = trimmed; stats.trimmed += 1; fileRepairs += 1; }
            continue;
          }
          if (!PROSE_KEYS.has(key)) continue;
          stats.clipped += 1;
          const restored = blocks.length ? restore(value.trimEnd(), blocks) : null;
          if (restored) {
            stats.repaired += 1;
            stats.charsAdded += restored.length - value.length;
            node[key] = restored;
            fileRepairs += 1;
          } else {
            stats.unmatched += 1;
            if (unmatchedSamples.length < 10) unmatchedSamples.push(`${gradeDir}/${file} ${key}: "${value.slice(-60)}"`);
          }
        } else visit(value);
      }
    };
    visit(unit);

    if (fileRepairs) {
      stats.changed += 1;
      if (write) fs.writeFileSync(filePath, `${JSON.stringify(unit, null, 2)}\n`, "utf8");
    }
  }
}

console.log(`${write ? "REPAIRED" : "DRY RUN"} — ${stats.files} unit files scanned`);
console.log(`  clipped prose fields found : ${stats.clipped}`);
console.log(`  restored from source       : ${stats.repaired}`);
console.log(`  left alone (no match)      : ${stats.unmatched}`);
console.log(`  summaries trimmed to a sentence : ${stats.trimmed}`);
console.log(`  files ${write ? "written" : "that would change"}       : ${stats.changed}`);
console.log(`  teaching text recovered    : ${stats.charsAdded.toLocaleString()} chars`);
if (unmatchedSamples.length) {
  console.log("\n  sample unmatched (left exactly as they were):");
  for (const sample of unmatchedSamples) console.log(`    ${sample}`);
}
if (!write) console.log("\nRe-run with --write to apply.");
